// Web Audio API Synthesizer (Chime Sound Effect)
let audioCtx = null;
function playChimeSound(type = 'success') {
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    if (!audioCtx) audioCtx = new AudioContext();
    if (audioCtx.state === 'suspended') audioCtx.resume();

    const now = audioCtx.currentTime;
    const osc = audioCtx.createOscillator();
    const gain = audioCtx.createGain();

    osc.connect(gain);
    gain.connect(audioCtx.destination);

    if (type === 'success') {
      // Pleasant high double chime
      osc.type = 'sine';
      osc.frequency.setValueAtTime(523.25, now); // C5
      osc.frequency.setValueAtTime(659.25, now + 0.1); // E5
      osc.frequency.setValueAtTime(783.99, now + 0.2); // G5
      gain.gain.setValueAtTime(0.2, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.6);
      osc.start(now);
      osc.stop(now + 0.6);
    } else if (type === 'timer_done') {
      // Celebration bell chime
      osc.type = 'triangle';
      osc.frequency.setValueAtTime(587.33, now); // D5
      osc.frequency.setValueAtTime(880.00, now + 0.15); // A5
      gain.gain.setValueAtTime(0.25, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.8);
      osc.start(now);
      osc.stop(now + 0.8);
    }
  } catch (e) {
    console.warn("Audio chime unsupported or blocked by browser policy:", e);
  }
}

// Global Toast Notifications
function showToast(message, type = 'info', duration = 4000) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast ${type}`;

  let iconSvg = ICONS.check;
  if (type === 'error') iconSvg = ICONS.alert;
  if (type === 'warning') iconSvg = ICONS.alert;
  if (type === 'rescue') iconSvg = ICONS.rescue;

  toast.innerHTML = `
    <span style="display:flex;align-items:center;">${iconSvg}</span>
    <div style="flex:1;font-size:0.88rem;font-weight:500;">${message}</div>
    <button style="background:none;border:none;color:currentColor;opacity:0.7;cursor:pointer;padding:2px;" onclick="this.parentElement.remove()">
      ${ICONS.close}
    </button>
  `;

  container.appendChild(toast);

  if (type === 'success' || type === 'rescue') {
    playChimeSound('success');
  }

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateX(50px)';
    toast.style.transition = 'all 0.3s ease';
    setTimeout(() => toast.remove(), 300);
  }, duration);
}

// Date & Time Helpers
function formatDate(isoStr) {
  if (!isoStr) return '';
  const d = new Date(isoStr);
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
}

function formatDeadlineRelative(isoStr) {
  if (!isoStr) return '';
  const now = new Date();
  const target = new Date(isoStr);
  const diffHours = (target - now) / (1000 * 60 * 60);

  if (diffHours < 0) {
    return `<span class="badge badge-urgent">Overdue</span>`;
  } else if (diffHours <= 24) {
    return `<span class="badge badge-urgent">Due in ${Math.round(diffHours)}h</span>`;
  } else if (diffHours <= 48) {
    return `<span class="badge badge-high">Due Tomorrow</span>`;
  } else {
    const days = Math.round(diffHours / 24);
    return `<span class="badge badge-medium">Due in ${days} days</span>`;
  }
}

// Markdown Formatter for AI Study Coach
function renderMarkdown(text) {
  if (!text) return '';
  let html = text
    .replace(/^### (.*$)/gim, '<h3 style="font-size:1.15rem;font-weight:700;color:#0f172a;margin:12px 0 6px 0;">$1</h3>')
    .replace(/^#### (.*$)/gim, '<h4 style="font-size:1rem;font-weight:700;color:#334155;margin:10px 0 4px 0;">$1</h4>')
    .replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/gim, '<em>$1</em>')
    .replace(/`([^`]+)`/gim, '<code style="background:#ede9fe;color:#5b21b6;padding:2px 6px;border-radius:4px;font-family:monospace;font-size:0.88em;">$1</code>')
    .replace(/^\- (.*$)/gim, '<li style="margin-left:18px;margin-bottom:4px;">$1</li>')
    .replace(/^\d+\. (.*$)/gim, '<li style="margin-left:18px;margin-bottom:4px;">$1</li>')
    .replace(/\n\n/gim, '<p style="margin-bottom:8px;"></p>');
  return html;
}
